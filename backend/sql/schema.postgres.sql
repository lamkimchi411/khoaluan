CREATE TABLE IF NOT EXISTS brands (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  keywords TEXT NOT NULL,
  threshold DOUBLE PRECISION NOT NULL DEFAULT 40,
  email TEXT NOT NULL DEFAULT '',
  telegram TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  video_id TEXT NOT NULL,
  brand_id BIGINT NOT NULL REFERENCES brands(id),
  caption TEXT NOT NULL DEFAULT '', author TEXT NOT NULL DEFAULT '', author_nickname TEXT,
  views BIGINT, likes BIGINT, comment_count BIGINT, shares BIGINT, saves BIGINT,
  video_url TEXT NOT NULL DEFAULT '', sentiment TEXT, score DOUBLE PRECISION,
  created_at TIMESTAMPTZ NOT NULL, observed_at TIMESTAMPTZ, published_at TIMESTAMPTZ,
  source TEXT NOT NULL DEFAULT 'live', collection_method TEXT, evidence_sha256 TEXT,
  hashtags TEXT, comment_status TEXT, discovery_keyword TEXT,
  UNIQUE(video_id, brand_id)
);

CREATE TABLE IF NOT EXISTS comments (
  id TEXT NOT NULL,
  post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  text TEXT NOT NULL, author TEXT NOT NULL DEFAULT '', author_nickname TEXT,
  parent_id TEXT, like_count BIGINT, sentiment TEXT, score DOUBLE PRECISION,
  created_at TIMESTAMPTZ NOT NULL, published_at TIMESTAMPTZ,
  PRIMARY KEY(id, post_id)
);

CREATE TABLE IF NOT EXISTS alerts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id BIGINT NOT NULL REFERENCES brands(id), reason TEXT NOT NULL,
  level TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'open',
  created_at TIMESTAMPTZ NOT NULL, delivery TEXT NOT NULL DEFAULT 'Chỉ thông báo trong ứng dụng'
);

CREATE TABLE IF NOT EXISTS jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id BIGINT NOT NULL REFERENCES brands(id), status TEXT NOT NULL,
  message TEXT NOT NULL DEFAULT '', report TEXT, created_at TIMESTAMPTZ NOT NULL,
  finished_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS crawl_schedules (
  brand_id BIGINT PRIMARY KEY REFERENCES brands(id), enabled BOOLEAN NOT NULL DEFAULT false,
  interval_minutes INTEGER NOT NULL DEFAULT 60, max_posts INTEGER NOT NULL DEFAULT 10,
  max_comments INTEGER NOT NULL DEFAULT 100, max_scrolls INTEGER NOT NULL DEFAULT 12,
  next_run_at TIMESTAMPTZ, last_run_at TIMESTAMPTZ, keyword_cursor INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS posts_brand_created_idx ON posts(brand_id, created_at DESC);
CREATE INDEX IF NOT EXISTS comments_post_idx ON comments(post_id);
CREATE INDEX IF NOT EXISTS alerts_brand_created_idx ON alerts(brand_id, created_at DESC);

CREATE TABLE IF NOT EXISTS staff (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, role TEXT NOT NULL, active BOOLEAN NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS tickets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, brand_id BIGINT NOT NULL REFERENCES brands(id), post_id BIGINT REFERENCES posts(id), comment_id TEXT,
  risk_score DOUBLE PRECISION NOT NULL, severity TEXT NOT NULL, queue TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'open', assignee_id BIGINT REFERENCES staff(id),
  created_at TIMESTAMPTZ NOT NULL, accepted_at TIMESTAMPTZ, resolved_at TIMESTAMPTZ, due_at TIMESTAMPTZ NOT NULL, escalated_at TIMESTAMPTZ, resolution_note TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS ticket_actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  actor TEXT NOT NULL, action TEXT NOT NULL, detail TEXT NOT NULL DEFAULT '', created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS ticket_responses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  content TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'approved', approved_by TEXT NOT NULL, approved_at TIMESTAMPTZ NOT NULL,
  published_at TIMESTAMPTZ, publish_mode TEXT, published_url TEXT
);
CREATE INDEX IF NOT EXISTS tickets_brand_status_idx ON tickets(brand_id, status, created_at DESC);
